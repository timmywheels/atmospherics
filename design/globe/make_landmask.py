"""Builds Atmospherics/LandMask.swift from Natural Earth's ne_110m_land.geojson.

Samples an even grid of points over the sphere (rows every STEP degrees of latitude,
spacing widened toward the poles so dots stay evenly spread) and keeps those on land.

    python3 -I make_landmask.py path/to/ne_110m_land.geojson ../../Atmospherics/LandMask.swift
"""
import json
import math
import sys

STEP = 2.4

def inside(lon, lat, ring):
    hit = False
    j = len(ring) - 1
    for i in range(len(ring)):
        xi, yi = ring[i][0], ring[i][1]
        xj, yj = ring[j][0], ring[j][1]
        if (yi > lat) != (yj > lat) and lon < (xj - xi) * (lat - yi) / (yj - yi) + xi:
            hit = not hit
        j = i
    return hit

def main(src, dst):
    polygons = []
    for feature in json.load(open(src))["features"]:
        geometry = feature["geometry"]
        parts = geometry["coordinates"] if geometry["type"] == "MultiPolygon" else [geometry["coordinates"]]
        for polygon in parts:
            outer, holes = polygon[0], polygon[1:]
            xs = [p[0] for p in outer]; ys = [p[1] for p in outer]
            polygons.append((min(xs), max(xs), min(ys), max(ys), outer, holes))

    points = []
    lat = -84.0
    while lat <= 84.0:
        count = max(1, int(round(360 / STEP * math.cos(math.radians(lat)))))
        for k in range(count):
            lon = -180 + (k + 0.5) * 360 / count
            for x0, x1, y0, y1, outer, holes in polygons:
                if x0 <= lon <= x1 and y0 <= lat <= y1 and inside(lon, lat, outer) \
                        and not any(inside(lon, lat, h) for h in holes):
                    points.append((round(lat, 2), round(lon, 2)))
                    break
        lat += STEP

    flat = ", ".join(f"{a}, {b}" for a, b in points)
    with open(dst, "w") as out:
        out.write("// Generated by design/globe/make_landmask.py from Natural Earth (public domain).\n")
        out.write("// Do not edit by hand.\n\n")
        out.write("/// Land, as (latitude, longitude) dots for the globe.\n")
        out.write("enum LandMask {\n")
        out.write("    static let points: [(Float, Float)] = {\n")
        out.write("        let flat: [Float] = [" + flat + "]\n")
        out.write("        return stride(from: 0, to: flat.count, by: 2).map { (flat[$0], flat[$0 + 1]) }\n")
        out.write("    }()\n}\n")
    print(f"{len(points)} land dots")

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
